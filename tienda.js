//==============================
// CARGAR PRODUCTOS
//==============================

function cargarProductos(lista = productos){

    const catalogo =
    document.getElementById("catalogoProductos");

    catalogo.innerHTML = "";

    lista.forEach(producto=>{

        let estrellas = "";

        for(let i=1;i<=5;i++){

            if(i<=producto.estrellas){

                estrellas+="⭐";

            }else{

                estrellas+="☆";

            }

        }

        let estado = "";

        if(producto.stock > 5){

            estado="🟢 Disponible";

        }

        else if(producto.stock >0){

            estado="🟠 Últimas unidades";

        }

        else{

            estado="🔴 Agotado";

        }

        catalogo.innerHTML += `

        <div class="card-producto">

            ${producto.nuevo ?

            `<div class="etiqueta">

                NUEVO

            </div>`

            :""}

            <div
class="favorito"
onclick="toggleFavorito(${producto.id})">

    ${
        favoritos.includes(producto.id)
        ? "❤️"
        : "🤍"
    }

</div>

            <img
            src="${producto.imagen}"
            alt="${producto.nombre}">

            <div class="info-producto">

                <h3>

                    ${producto.nombre}

                </h3>

                <p class="marca">

                    ${producto.marca}

                </p>

                <div class="estrellas">

                    ${estrellas}

                </div>

                <p class="precio">

                    $${producto.precio.toLocaleString()}

                </p>

                <p class="estado">

                    ${estado}

                </p>

                <button
                class="btn-ver"
                onclick="abrirProducto(${producto.id})">

                    Ver detalles

                </button>

            </div>

        </div>

        `;

    });

}

//==============================
// MODAL
//==============================

let productoActual=null;

//==============================
// CARRITO
//==============================

let carrito = JSON.parse(localStorage.getItem("carrito")) || [];

let favoritos = JSON.parse(localStorage.getItem("favoritos")) || [];

function abrirProducto(id){

    productoActual=
    productos.find(p=>p.id===id);

    document.getElementById("imagenProducto").src=
    productoActual.imagen;

    document.getElementById("nombreProducto").innerHTML=
    productoActual.nombre;

    document.getElementById("marcaProducto").innerHTML=
    "Marca: "+productoActual.marca;

    document.getElementById("precioProducto").innerHTML=
    "$"+productoActual.precio.toLocaleString();

    document.getElementById("descripcionProducto").innerHTML=
    productoActual.descripcion;

    document.getElementById("cantidadProducto").value=1;

    document.getElementById("modalProducto").style.display="flex";

}

function cerrarProducto(){

    document.getElementById("modalProducto").style.display="none";

}

//==============================
// CARRITO (TEMPORAL)
//==============================

function agregarCarrito(){

    const cantidad = parseInt(
        document.getElementById("cantidadProducto").value
    );

    const existe = carrito.find(
        item => item.id === productoActual.id
    );

    if(existe){

        existe.cantidad += cantidad;

    }else{

        carrito.push({

            ...productoActual,

            cantidad

        });

    }

    localStorage.setItem("pedido", JSON.stringify(carrito));

    actualizarCarrito();

    mostrarNotificacion();

    cerrarProducto();

}

//==============================
// ACTUALIZAR CARRITO
//==============================

function actualizarCarrito(){

    const lista =
    document.getElementById("listaCarrito");

    const contador =
    document.getElementById("contadorCarrito");

    const total =
    document.getElementById("totalCarrito");

    lista.innerHTML = "";

    let totalCompra = 0;

    let totalProductos = 0;

    carrito.forEach(producto=>{

        totalCompra +=
        producto.precio * producto.cantidad;

        totalProductos +=
        producto.cantidad;

        lista.innerHTML += `

        <div class="item-carrito">

            <img src="${producto.imagen}">

            <div>

                <h4>${producto.nombre}</h4>

        <div class="cantidad-carrito">

    <button
    onclick="cambiarCantidad(${producto.id},-1)">

        -

    </button>

    <span>

        ${producto.cantidad}

    </span>

    <button
    onclick="cambiarCantidad(${producto.id},1)">

        +

    </button>

</div>
<p>

    $${(producto.precio * producto.cantidad).toLocaleString()}

</p>

                <button
                onclick="eliminarProducto(${producto.id})">

                    Eliminar

                </button>

            </div>

        </div>

        `;

    });

    contador.innerHTML = totalProductos;

    total.innerHTML =
    "$" + totalCompra.toLocaleString();

    localStorage.setItem("carrito", JSON.stringify(carrito));

    localStorage.setItem("pedido", JSON.stringify(carrito));

}

//==============================
// ELIMINAR
//==============================

function eliminarProducto(id){

    carrito = carrito.filter(

        producto => producto.id !== id

    );

    actualizarCarrito();

}


//==============================
// CAMBIAR CANTIDAD
//==============================

function cambiarCantidad(id,cambio){

    const producto =
    carrito.find(item=>item.id===id);

    if(!producto) return;

    producto.cantidad += cambio;

    if(producto.cantidad<=0){

        eliminarProducto(id);

        return;

    }

    actualizarCarrito();

}

//==============================
// ABRIR Y CERRAR
//==============================

function abrirCarrito(){

    document
    .getElementById("carrito")
    .classList.add("activo");

}

function cerrarCarrito(){

    document
    .getElementById("carrito")
    .classList.remove("activo");

}

//==============================
// NOTIFICACIÓN
//==============================

function mostrarNotificacion(){

    const aviso =
    document.getElementById("notificacion");

    aviso.classList.add("mostrar");

    setTimeout(()=>{

        aviso.classList.remove("mostrar");

    },2000);

}

//==============================
// FAVORITOS
//==============================

function toggleFavorito(id){

    if(favoritos.includes(id)){

        favoritos =
        favoritos.filter(item => item !== id);

    }else{

        favoritos.push(id);

    }

    localStorage.setItem(

        "favoritos",

        JSON.stringify(favoritos)

    );

    cargarProductos();

}

//==============================

document.addEventListener("DOMContentLoaded",()=>{

    cargarProductos(productos);

    actualizarCarrito();

});


//==============================
// BUSCADOR
//==============================

const buscador =
document.getElementById("buscarProducto");

buscador.addEventListener("keyup",()=>{

    const texto =
    buscador.value.toLowerCase();

    const filtrados =
    productos.filter(producto=>

        producto.nombre.toLowerCase().includes(texto) ||

        producto.marca.toLowerCase().includes(texto) ||

        producto.categoria.toLowerCase().includes(texto)

    );

    cargarProductos(filtrados);

});


//==============================
// CATEGORÍAS
//==============================

const botonesCategorias =
document.querySelectorAll(".categorias-tienda button");

botonesCategorias.forEach(boton=>{

    boton.addEventListener("click",()=>{

        botonesCategorias.forEach(btn=>{

            btn.classList.remove("activo");

        });

        boton.classList.add("activo");

        const categoria =
        boton.dataset.categoria;

        if(categoria==="Todos"){

            cargarProductos(productos);

            return;

        }

        const filtrados =
        productos.filter(producto=>

            producto.categoria===categoria ||

            producto.genero===categoria

        );

        cargarProductos(filtrados);

    });

});

//==============================
// FINALIZAR COMPRA
//==============================

function finalizarCompra(){

    if(carrito.length===0){

        alert("Tu carrito está vacío.");

        return;

    }

    localStorage.setItem(

        "pedido",

        JSON.stringify(carrito)

    );

    window.location.href="checkout.html";

}


//==============================
// IR AL CHECKOUT
//==============================

function irCheckout(){

    if(carrito.length === 0){

        alert("Tu carrito está vacío.");

        return;

    }

    localStorage.setItem(
        "pedido",
        JSON.stringify(carrito)
    );

    window.location.href = "checkout.html";

}

